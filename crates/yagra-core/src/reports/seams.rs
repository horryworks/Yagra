//! What making a report is allowed to reach, expressed as three traits (ADR-112).
//!
//! Before this file [`super::ReportRunner`] held four PostgreSQL-backed concrete types, and that
//! is why **521 production lines shipped with no tests**: not because nobody wrote them, but
//! because no test could construct the value they are methods on. ADR-102 decision 5 measured
//! that and stopped rather than turn a file split into a rewrite; this is the rest of it.
//!
//! The traits are cut by **what the caller needs**, never per repository (ADR-092 decision 1) —
//! thirteen methods against four concrete types with a hundred-odd between them. The same shape
//! as `analysis/seams.rs` (ADR-098) and `scheduler/seams.rs` (ADR-111).
//!
//! 🎯 **[`AlertFacts`] spans two stores on purpose.** `render_alert_summary` needs the live alerts
//! *and* the history inside one section — "active now" beside "fires in the window" is the whole
//! point of that table. Splitting it in two would be cutting per repository, which is the thing
//! the rule above forbids.
//!
//! 🎯 **[`AlertFacts::recent_history`] takes only a limit.** The real method takes
//! `(limit, before, before_id)` for keyset paging, and the one caller here has always passed
//! `(1000, None, None)`. Paging is not something a report does.
//!
//! ⚠️ **[`FleetInventory::node_names`] keeps its scope argument.** The only caller passes
//! "unrestricted", and it carries three lines saying why: a report is an admin-defined, fleet-wide
//! artefact generated by a background task with no requesting principal (ADR-014 non-goal).
//! Baking that `None` into the implementation below would move the decision out of reach of a
//! test — the mistake ADR-111 avoided by cutting the credential seam at the *sealed* bytes rather
//! than at a resolved credential.
//!
//! ⚠️ What this does **not** buy: [`super::ReportsRepo`] is 479 lines of SQL, so a fake
//! [`RunStore`] proves the runner *calls* it and never that the statement is right. That is the
//! same limit `repo/` has, and it is not a shape problem.

